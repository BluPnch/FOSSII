"""
Исследование 3: какой размер окна пулинга лучше.

Сравниваются четыре сети с одинаковыми свёртками (8 и 16 фильтров 3×3),
которые отличаются только окном обоих пулингов:

    окно 2×2:  28 → conv 26 → pool 13 → conv 11 → pool 5   → 16·5·5 = 400 признаков
    окно 3×3:  28 → conv 26 → pool 12 → conv 10 → pool 4   → 16·4·4 = 256 признаков
    окно 4×4:  28 → conv 26 → pool 12 → conv 10 → pool 4   → 16·4·4 = 256 признаков
    окно 5×5:  28 → conv 26 → pool 11 → conv 9  → pool 3   → 16·3·3 = 144 признака

Шаг пулинга у всех один и тот же - 2. Начиная с 3×3 окна перекрываются
(соседние окна делят часть пикселей), и меняется только то, из какой
области берётся максимум, а не во сколько раз сжимается карта.

Почему не шаг, равный окну (как в основной сети): тогда при окне 4×4
после второго пулинга осталась бы карта 1×1, а окно 5×5 вообще не
поместилось бы - после второй свёртки карта всего 3×3.

Вариант 2×2 - основная сеть лабораторной.

Запуск (из этой папки):

    python pooling_window.py
    python pooling_window.py --train-size 1000 --epochs 2   быстрая проверка

Результаты: results/investigations/pooling_window/
"""

from common import parse_args, run_investigation


STRIDE = 2

# Цвет закреплён за вариантом и одинаков на всех графиках;
# основная сеть - синяя, как и в других исследованиях
VARIANTS = [
    {
        "key": f"pool_{size}",
        "label": f"окно {size}×{size}",
        "filters": [8, 16],
        "pools": [(size, STRIDE), (size, STRIDE)],
        "color": color,
    }
    for size, color in [
        (2, "#2a78d6"),
        (3, "#eb6834"),
        (4, "#1baf7a"),
        (5, "#4a3aa7"),
    ]
]


if __name__ == "__main__":
    run_investigation(
        "pooling_window",
        "Окно пулинга",
        VARIANTS,
        parse_args(),
    )
